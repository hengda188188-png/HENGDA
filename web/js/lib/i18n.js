const LANG = 'zh-Hant';

export function t(key, vars) {
  const raw = DICT[LANG][key];
  if (raw === undefined) {
    console.warn('[i18n] 缺少字典鍵：', key);
    return key;
  }
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
}

